"""app/api/models_report.py — Model evaluation report endpoint.

Reads models/report.json generated by `make train` and returns it.
Also provides a live endpoint for basic model status.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from fastapi import APIRouter, HTTPException

router = APIRouter()

PROJECT_ROOT = Path(__file__).resolve().parents[3]
MODELS_DIR = Path(os.getenv("TRUSTHEAL_MODELS_DIR", str(PROJECT_ROOT / "models"))).expanduser()
if not MODELS_DIR.is_absolute():
    MODELS_DIR = PROJECT_ROOT / MODELS_DIR


def _wilson_interval(successes: int, total: int) -> tuple[float | None, float | None]:
    if total == 0:
        return None, None
    z = 1.96
    proportion = successes / total
    denominator = 1 + z * z / total
    center = (proportion + z * z / (2 * total)) / denominator
    margin = z * ((proportion * (1 - proportion) / total + z * z / (4 * total * total)) ** 0.5) / denominator
    return max(0.0, center - margin), min(1.0, center + margin)


@router.get("/models/report")
async def get_models_report():
    """Return the full evaluation report from models/report.json."""
    report_path = MODELS_DIR / "report.json"
    if not report_path.exists():
        raise HTTPException(
            404,
            "models/report.json not found — run `make train` first",
        )
    with open(report_path, encoding="utf-8") as f:
        data = json.load(f)

    classification = data.get("classification_report", {})
    data.setdefault("per_class", {
        label: {
            "precision": metrics["precision"],
            "recall": metrics["recall"],
            "f1": metrics["f1-score"],
            "support": metrics["support"],
        }
        for label, metrics in classification.items()
        if isinstance(metrics, dict) and "f1-score" in metrics
    })
    data.setdefault("weighted_avg", {
        key: classification.get("weighted avg", {}).get(source)
        for key, source in (("precision", "precision"), ("recall", "recall"), ("f1", "f1-score"))
    })
    data.setdefault("macro_avg", {
        key: classification.get("macro avg", {}).get(source)
        for key, source in (("precision", "precision"), ("recall", "recall"), ("f1", "f1-score"))
    })

    if "unseen_fault_results" not in data:
        unseen = data.get("unseen_faults", {})
        total = int(unseen.get("total", 0))
        wrongly_automated = int(unseen.get("wrongly_auto", 0))
        ci_lower, ci_upper = _wilson_interval(wrongly_automated, total)
        data["unseen_fault_results"] = {
            "total": total,
            "escalated": int(unseen.get("escalated", 0)),
            "wrongly_automated": wrongly_automated,
            "wrongly_auto_rate": wrongly_automated / total if total else None,
            "wilson_ci_lower": ci_lower,
            "wilson_ci_upper": ci_upper,
            "n_unseen_samples": total,
        }
    return data


@router.get("/models/status")
async def get_models_status():
    """Return which model artefacts are present."""
    artefacts = {
        "dataset":    (MODELS_DIR / "dataset.npz").exists(),
        "mlp":        (MODELS_DIR / "mlp_mcd.pt").exists(),
        "xgb":        (MODELS_DIR / "xgb.json").exists(),
        "iforest":    (MODELS_DIR / "iforest.joblib").exists(),
        "autoencoder":(MODELS_DIR / "autoencoder.pt").exists(),
        "thresholds": (MODELS_DIR / "thresholds.json").exists(),
        "report":     (MODELS_DIR / "report.json").exists(),
    }
    all_present = all(artefacts.values())
    return {
        "all_present": all_present,
        "artefacts": artefacts,
    }
